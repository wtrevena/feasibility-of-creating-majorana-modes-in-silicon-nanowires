# ------------------------------------------------------------------ sections
def sec_A():
    """Validation gauntlet a-e. All must pass before physics sections."""
    t0 = time.time()
    out, ok = {}, True

    # (a) bulk band edges at k = 0
    ev = np.linalg.eigvalsh(bulk_H6((0.0, 0.0, 0.0)))
    g8 = np.abs(ev[:4]).max() / MEV_J
    g7 = ev[4:] / MEV_J
    pa = g8 < 1e-12 and np.abs(g7 - DSO_MEV).max() < 1e-10
    out["a_bulk_k0"] = dict(
        gamma8_max_abs_meV=float(g8),
        gamma7_meV=[float(x) for x in g7],
        note="hole picture: Gamma7 at +44 meV == -44 meV electron picture",
        passed=bool(pa))
    ok &= pa

    # (b) bulk [100] HH mass + closed-form HH/(LH-SO) branches [001], [111]
    kmag = 2.3e8
    kt = HBAR**2 * kmag**2 / (2 * M0)
    dev = 0.0
    for axis, gg in (((0, 0, 1), G2), ((1, 1, 1), G3)):
        n = np.array(axis, float)
        n /= np.linalg.norm(n)
        ev = np.linalg.eigvalsh(bulk_H6(tuple(n * kmag)))
        hh = (G1 - 2 * gg) * kt
        m22 = np.array([[(G1 + 2 * gg) * kt, 2 * np.sqrt(2) * gg * kt],
                        [2 * np.sqrt(2) * gg * kt,
                         G1 * kt + DSO_MEV * MEV_J]])
        e2 = np.linalg.eigvalsh(m22)
        expect = np.sort([hh, hh, e2[0], e2[0], e2[1], e2[1]])
        dev = max(dev, float(np.abs((ev - expect) / expect).max()))
    m_hh = 1.0 / (G1 - 2 * G2)
    pb = dev < 1e-10
    out["b_bulk_branches"] = dict(
        m_hh_100=float(round(m_hh, 4)), expect=0.2773,
        max_rel_dev_vs_closed_form_001_111=dev,
        passed=bool(pb))
    ok &= pb

    # internal basis/corner identities (random k, fixed seed)
    rng = np.random.default_rng(7)
    crn = 0.0
    for _ in range(5):
        kv = rng.uniform(-3e8, 3e8, 3)
        H6b = bulk_H6(tuple(kv))
        scale = np.abs(H6b).max()
        crn = max(crn, np.abs(H6b[:4, :4] - _lk_bulk4(*kv)).max() / scale)
        g7blk = H6b[4:, 4:] - DSO_MEV * MEV_J * np.eye(2)
        e7 = HBAR**2 / (2 * M0) * G1 * (kv @ kv)
        crn = max(crn, np.abs(g7blk - e7 * np.eye(2)).max() / scale)
    pi = crn < 1e-12
    out["internal_corner_identities"] = dict(max_rel_dev=float(crn),
                                             passed=bool(pi))
    ok &= pi

    # (c) Delta_so -> infinity, lk-identical FD operators, same grid:
    # must reproduce lk_holes.extract (pins every convention choice)
    six = extract6(PROD["Ez"], Dso_meV=1e6, basis="fd")
    four = lk_holes.extract(PROD["Ez"])
    diffs = {n: round(_pct(six[i], four[i]), 4) for i, n in enumerate(NAMES)}
    pc = max(diffs.values()) < 2.0
    out["c_dso_inf_limit_fd"] = dict(
        six_band={n: round(six[i], 4) for i, n in enumerate(NAMES)},
        four_band={n: round(four[i], 4) for i, n in enumerate(NAMES)},
        pct_diff=diffs, passed=bool(pc))
    ok &= pc

    # (c2) discretization cross-check at the physical Delta_so: the FD
    # results on refining grids must approach the sine-basis values
    dst = extract6(PROD["Ez"])                      # production: dst 11x13
    fd_seq = {}
    for g in ((11, 13), (15, 17), (19, 21)):
        fd_seq[f"{g[0]}x{g[1]}"] = extract6(PROD["Ez"], ny=g[0], nz=g[1],
                                            basis="fd")
        print(f"  A/c2: fd {g} done t={time.time()-t0:.0f}s", flush=True)
    d_first = {n: _pct(fd_seq["11x13"][i], dst[i])
               for i, n in enumerate(NAMES)}
    d_last = {n: _pct(fd_seq["19x21"][i], dst[i])
              for i, n in enumerate(NAMES)}
    pc2 = all(d_last[n] < d_first[n] for n in NAMES)
    out["c2_fd_to_dst_crosscheck"] = dict(
        dst_11x13={n: round(dst[i], 4) for i, n in enumerate(NAMES)},
        fd_sequence={g: {n: round(r[i], 4) for i, n in enumerate(NAMES)}
                     for g, r in fd_seq.items()},
        fd_minus_dst_pct_coarse={n: round(v, 2) for n, v in d_first.items()},
        fd_minus_dst_pct_fine={n: round(v, 2) for n, v in d_last.items()},
        passed=bool(pc2))
    ok &= pc2

    # (d) Kramers degeneracy at B = 0, kx = 0, any Ez (production basis)
    worst = 0.0
    for Ez in (0.0, PROD["Ez"], 2.5e7):
        ev = np.linalg.eigvalsh(build_fin_H6(0.0, Ez))
        for i in range(30):
            split = ev[2 * i + 1] - ev[2 * i]
            spacing = ev[2 * i + 2] - ev[2 * i]
            if spacing > 0:
                worst = max(worst, split / spacing)
    pd = worst < 1e-10
    out["d_kramers"] = dict(max_split_over_spacing=float(worst),
                            passed=bool(pd))
    ok &= pd

    # (e) hermiticity + basis-size convergence (production basis)
    herm = 0.0
    for bas in ("fd", "dst"):
        H = build_fin_H6(2e7, 3e7, (0.05, 0.05, 0.05), basis=bas)
        herm = max(herm, float(np.abs(H - H.conj().T).max()))
    fine = extract6(PROD["Ez"], ny=PROD["ny"] + 4, nz=PROD["nz"] + 4)
    conv = {n: round(_pct(dst[i], fine[i]), 3) for i, n in enumerate(NAMES)}
    pe = herm < 1e-25 and max(conv.values()) < 3.0
    out["e_herm_convergence"] = dict(
        max_nonhermiticity_J=herm,
        dst_change_pct_11x13_vs_15x17_modes=conv, passed=bool(pe))
    ok &= pe

    out["all_passed"] = bool(ok)
    out["runtime_s"] = round(time.time() - t0, 1)
    return out


