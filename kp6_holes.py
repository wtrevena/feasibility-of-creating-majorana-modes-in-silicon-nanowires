"""
kp6_holes.py — 6-band k.p (Luttinger-Kohn-Bir-Pikus, Gamma8+Gamma7) model of
the Si FinFET hole channel: the first theory upgrade flagged in lk_holes.py.

Question answered: silicon's split-off gap Delta_so = 44 meV is comparable to
the fin confinement energies (tens of meV at 7-16 nm), so the 4-band model's
underprediction of the wire-axis g-factor (g_x in [0.4, 1.1] vs measured
1.9-2.3, Geyer 2024) may be a split-off-coupling artifact. This module builds
the full 6x6 model with the same extraction conventions as lk_holes.py so the
two are exactly swappable, and quantifies how Delta_so moves (m*, alpha,
g-tensor).

CONVENTIONS (referee checklist)
-------------------------------
* Hole picture, energies POSITIVE into the valence band, exactly as
  lk_holes.py: the lowest eigenvalues of H are the topmost valence states.
  Consequently the split-off (Gamma7) band sits at +Delta_so = +44 meV in our
  spectra (equivalently -44 meV in the electron picture).
* Basis: |J,mJ> = |3/2,+3/2>, |3/2,+1/2>, |3/2,-1/2>, |3/2,-3/2>,
  |1/2,+1/2>, |1/2,-1/2>, built from |X,Y,Z> x |up,down> with Condon-Shortley
  Clebsch-Gordan phases and e_{+1} = -(x+iy)/sqrt2. With these phases the
  Gamma8 block of the total angular momentum J = L + S reproduces the
  spin-3/2 matrices JX, JY, JZ of lk_holes.py to machine precision (asserted
  at import), so all 4-band and 6-band expectation values are directly
  comparable.
* Kinetic term: the p-multiplet orbital Hamiltonian H_ab = [L ka^2
  + M (kb^2+kc^2)] delta_ab + N {ka,kb} (a,b in x,y,z; {,} symmetrized), with
  hole-picture L = (hbar^2/2m0)(g1+4 g2), M = (hbar^2/2m0)(g1-2 g2),
  N = (hbar^2/2m0) 6 g3, rotated to the |J,mJ> basis. Its Gamma8 projection
  is EXACTLY the 4-band LK Hamiltonian of lk_holes.py (full cubic anisotropy,
  no axial approximation; asserted at import); its Gamma7 projection is
  (hbar^2/2m0) g1 k^2 (+Delta_so); the Gamma8-Gamma7 coupling blocks are the
  standard Chao-Chuang / Winkler P,Q,R,S combinations — all three follow from
  the one L,M,N matrix, so the coupling phases are consistent by
  construction. Validation: the bulk 6x6 reproduces the closed-form
  HH/(LH-SO) dispersions along [001] and [111] (coupling elements
  2*sqrt2*g2*k~^2 and 2*sqrt2*g3*k~^2) to machine precision.
* No double counting: the Luttinger gammas are Gamma8 band-edge parameters
  generated by REMOTE bands (Gamma6c etc.); the explicit Gamma8-Gamma7
  coupling added here is internal to the p multiplet and contributes to
  Gamma8 energies only at order k^4/Delta_so (nothing at the band edge), so
  using the same Lawaetz gammas (4.285, 0.339, 1.446) in the 6-band model is
  the standard prescription (Chao-Chuang 1992; Winkler 2003) and involves no
  double counting.
* Zeeman: written as H_Z = mu_B (g_L^h B.L + g_s^h B.S) within the
  6-dim multiplet (hole picture), with g_s^h = -2 (bare spin, sign flipped by
  the hole convention) and g_L^h = 3 kappa + 1 fixed by requiring the Gamma8
  projection to equal lk_holes' +2 kappa mu_B B.J (projection theorem:
  P8 L P8 = (2/3) J, P8 S P8 = (1/3) J). This reproduces Luttinger's
  kappa = -2/3 atomic limit (g_L^h = -1, pure-p multiplet) and implies the
  Gamma7 block H_Z(Gamma7) = 2(2 kappa + 1) mu_B B.sigma/2 in our hole
  convention (electron-picture Gamma7 g-factor -2(2 kappa + 1), the Winkler
  "-2(kappa + ...)" form), plus the Gamma8-Gamma7 Zeeman coupling block, both
  generated automatically by the same L,S decomposition (asserted at import).
  The cubic q J^3 term is neglected (q ~ 0.01 in Si), as in lk_holes.py.
* Orbital magnetic field: vector-potential (Peierls) substitution
  k -> k + eA/hbar with A = (B_y z - B_z y, 0, B_x y) inside the transverse
  momentum operators, with the identical operator formulas of
  lk_holes.build_fin_H, so orbital and bare Zeeman effects enter the 6-band
  g-tensor on exactly the same footing as in the 4-band model.
* Geometry: hard-wall rectangular fin (y = width, z = vertical), wire along
  x = [100] (crystal axes), vertical gate field U = +e E_z z (identical sign
  to lk_holes).

TWO DISCRETIZATIONS (why both exist)
------------------------------------
* basis="fd": symmetrized central finite differences on the interior grid,
  line-for-line the operators of lk_holes.build_fin_H. Used for validation
  (c): with Delta_so -> infinity the 6-band model must reproduce
  lk_holes.extract at the same grid — it does to < 0.01 %, which pins every
  basis/coupling/Zeeman convention against the 4-band code.
* basis="dst" (production): hard-wall sine (Galerkin) basis: -d2/dx2 is
  exact and diagonal, -i d/dx and the position operator use the analytic
  sine-basis matrix elements. Same continuum Hamiltonian, near-spectral
  convergence. This is needed because at the physical Delta_so = 44 meV the
  Gamma8-Gamma7 mixing is strong (confinement energies ~ Delta_so) and
  amplifies the O(d^2) FD error: the FD extraction outputs still drift 6-9 %
  between an 11x13 and a 15x17 grid, never reaching the < 3 % convergence
  gate at affordable sizes, while the sine basis passes it at 11x13 modes.
  Validation A cross-checks the two: the FD results on refining grids
  (11x13 -> 15x17 -> 19x21) must approach the converged sine-basis values.

extract6(Ez, ...) returns (m*/m0, alpha_eVA, gx, gy, gz, nso) for the lowest
Kramers doublet with the identical recipes of lk_holes.extract (kx curvature
at k1 = 2e7/m, linear-in-kx splitting for alpha, B = 0.05 T field derivative
of the doublet splitting for g, <J> of the kx-split doublet for the SOC
axis), so downstream code can swap the models.

Checkpointing: results cached per-section in output/data/kp6.json; reruns
skip finished sections (--force to redo). Key numbers go to the repo ledger
via run_analysis.save_numbers("kp6", ...).

Sections (python kp6_holes.py --sec A|B|C|D|all):
  A  validation gauntlet (bulk edges, [100] HH mass, closed-form LH-SO
     branches, Delta_so->inf vs lk_holes, FD->sine cross-check, Kramers,
     hermiticity, basis-size convergence) — must pass before B-D run;
  B  extract6 vs Ez in {2,5,10,15,20,30,40,50} MV/m at 10x12 nm (fig10 table);
  C  seven-geometry bracket (fig10 g_bracket list) — 6-band g_x range;
  D  Delta_so sensitivity at the production point: 44 / 100 / 300 / 1e6 meV.
"""

