# --------------------------------------------------------------- basis setup
def _ket(ml, sdn):
    """|1,ml>|spin> in the (X up, Y up, Z up, X dn, Y dn, Z dn) basis."""
    e = {+1: np.array([-1.0, -1.0j, 0.0]) / np.sqrt(2.0),
         0:  np.array([0.0, 0.0, 1.0], dtype=complex),
         -1: np.array([1.0, -1.0j, 0.0]) / np.sqrt(2.0)}[ml]
    v = np.zeros(6, complex)
    v[3 * sdn:3 * sdn + 3] = e
    return v


_r13, _r23 = np.sqrt(1.0 / 3.0), np.sqrt(2.0 / 3.0)
U6 = np.column_stack([
    _ket(+1, 0),                                  # |3/2,+3/2>
    _r13 * _ket(+1, 1) + _r23 * _ket(0, 0),       # |3/2,+1/2>
    _r23 * _ket(0, 1) + _r13 * _ket(-1, 0),       # |3/2,-1/2>
    _ket(-1, 1),                                  # |3/2,-3/2>
    _r23 * _ket(+1, 1) - _r13 * _ket(0, 0),       # |1/2,+1/2>
    _r13 * _ket(0, 1) - _r23 * _ket(-1, 0),       # |1/2,-1/2>
])

LX3 = np.array([[0, 0, 0], [0, 0, -1j], [0, 1j, 0]], complex)
LY3 = np.array([[0, 0, 1j], [0, 0, 0], [-1j, 0, 0]], complex)
LZ3 = np.array([[0, -1j, 0], [1j, 0, 0], [0, 0, 0]], complex)
SX2 = 0.5 * np.array([[0, 1], [1, 0]], complex)
SY2 = 0.5 * np.array([[0, -1j], [1j, 0]], complex)
SZ2 = 0.5 * np.array([[1, 0], [0, -1]], complex)
I2, I3 = np.eye(2, dtype=complex), np.eye(3, dtype=complex)
I6 = np.eye(6, dtype=complex)
P7 = np.diag([0., 0., 0., 0., 1., 1.]).astype(complex)

Lj = [U6.conj().T @ np.kron(I2, La) @ U6 for La in (LX3, LY3, LZ3)]
Sj = [U6.conj().T @ np.kron(Sa, I3) @ U6 for Sa in (SX2, SY2, SZ2)]
J6 = [l + s for l, s in zip(Lj, Sj)]


def _E3(a, b):
    m = np.zeros((3, 3), complex)
    m[a, b] = 1.0
    return m


CAB = [[U6.conj().T @ np.kron(I2, _E3(a, b)) @ U6 for b in range(3)]
       for a in range(3)]

# Zeeman decomposition (see docstring): hole picture
GS_H = -2.0
GL_H = 3.0 * KAPPA + 1.0


def _zeeman6(B):
    return MU_B_J * sum(Bi * (GL_H * Li + GS_H * Si)
                        for Bi, Li, Si in zip(B, Lj, Sj))


# import-time consistency asserts (basis phases vs lk_holes)
def _basis_selfcheck():
    assert np.abs(U6.conj().T @ U6 - I6).max() < 1e-14, "U6 not unitary"
    for Jfull, Jlk in zip(J6, (JX, JY, JZ)):
        assert np.abs(Jfull[:4, :4] - Jlk).max() < 1e-14, "Gamma8 J mismatch"
        assert np.abs(Jfull[:4, 4:]).max() < 1e-14, "J couples G8-G7"
    for Jfull, S2 in zip(J6, (SX2, SY2, SZ2)):
        assert np.abs(Jfull[4:, 4:] - S2).max() < 1e-14, "Gamma7 J mismatch"
    for Li, Si, Jlk, S2 in zip(Lj, Sj, (JX, JY, JZ), (SX2, SY2, SZ2)):
        Z = GL_H * Li + GS_H * Si
        assert np.abs(Z[:4, :4] - 2 * KAPPA * Jlk).max() < 1e-13, \
            "Gamma8 Zeeman != 2 kappa J"
        assert np.abs(Z[4:, 4:] - 2 * (2 * KAPPA + 1) * S2).max() < 1e-13, \
            "Gamma7 Zeeman != 2(2kappa+1) sigma/2"


_basis_selfcheck()


# --------------------------------------------------------------- bulk model
def _LMN():
    pref = HBAR**2 / (2 * M0)
    return pref * (G1 + 4 * G2), pref * (G1 - 2 * G2), pref * 6 * G3


def bulk_H6(k, Dso_meV=DSO_MEV):
    """Bulk 6x6 at numeric k = (kx,ky,kz), hole picture (Joules)."""
    Lp, Mp, Np = _LMN()
    kx, ky, kz = k
    Hor = np.array([
        [Lp * kx * kx + Mp * (ky * ky + kz * kz), Np * kx * ky, Np * kx * kz],
        [Np * kx * ky, Lp * ky * ky + Mp * (kx * kx + kz * kz), Np * ky * kz],
        [Np * kx * kz, Np * ky * kz, Lp * kz * kz + Mp * (kx * kx + ky * ky)],
    ], dtype=complex)
    return (U6.conj().T @ np.kron(I2, Hor) @ U6
            + Dso_meV * MEV_J * P7)


def _lk_bulk4(kx, ky, kz):
    """lk_holes-convention bulk 4x4 (for the Gamma8-corner identity check)."""
    pref = HBAR**2 / (2 * M0)
    k2 = kx * kx + ky * ky + kz * kz
    return pref * ((G1 + 2.5 * G2) * k2 * I4
                   - 2 * G2 * (kx * kx * (JX @ JX) + ky * ky * (JY @ JY)
                               + kz * kz * (JZ @ JZ))
                   - 4 * G3 * (kx * ky * _sym(JX, JY) + ky * kz * _sym(JY, JZ)
                               + kz * kx * _sym(JZ, JX)))


# ----------------------------------------------------------------- fin model
def _dst_ops(n, W):
    """Hard-wall sine-basis 1D operators (modes m = 1..n on [0, W]):
    exact -d2/dx2 (diagonal), analytic <m|-i d/dx|n> and centered position."""
    m = np.arange(1, n + 1)
    K2 = np.diag((m * np.pi / W) ** 2)
    a = m[:, None].astype(float)
    b = m[None, :].astype(float)
    odd = (m[:, None] + m[None, :]) % 2 == 1
    with np.errstate(divide="ignore", invalid="ignore"):
        D1 = np.where(odd, 4.0 * a * b / (W * (a * a - b * b)), 0.0)
        X = np.where(odd, -2.0 * W / np.pi**2
                     * (1.0 / (a - b) ** 2 - 1.0 / (a + b) ** 2), 0.0)
    np.fill_diagonal(D1, 0.0)
    np.fill_diagonal(X, 0.0)          # centered: <m|y - W/2|m> = 0
    return K2, D1, X


def build_fin_H6(kx, Ez_Vm=0.0, B=(0.0, 0.0, 0.0),
                 Wy=10e-9, Wz=12e-9, ny=11, nz=13, Dso_meV=DSO_MEV,
                 basis="dst"):
    """Dense 6*ny*nz Hamiltonian of the fin cross-section at wire momentum
    kx. basis="fd": lk_holes-identical grid operators (ny x nz interior
    points); basis="dst": hard-wall sine basis (ny x nz modes). Field signs
    and Peierls substitution identical to lk_holes.build_fin_H. Energies in
    Joules (hole picture, positive)."""
    Iy, Iz = np.eye(ny), np.eye(nz)
    Ig = np.eye(ny * nz)
    Bx, By, Bz = B
    c = QE / HBAR
    if basis == "fd":
        dy, dz = Wy / (ny + 1), Wz / (nz + 1)
        y = (np.arange(ny) + 1) * dy - Wy / 2
        z = (np.arange(nz) + 1) * dz - Wz / 2
        Yd = np.kron(np.diag(y), Iz)
        Zd = np.kron(Iy, np.diag(z))
        KYb = -1j * np.kron(_d1(ny, dy), Iz)
        KZb = -1j * np.kron(Iy, _d1(nz, dz))
        KY2 = -np.kron(_d2(ny, dy), Iz) + 0j
        KZ2b = -np.kron(Iy, _d2(nz, dz)) + 0j
    elif basis == "dst":
        K2y, D1y, Xy = _dst_ops(ny, Wy)
        K2z, D1z, Xz = _dst_ops(nz, Wz)
        Yd = np.kron(Xy, Iz)
        Zd = np.kron(Iy, Xz)
        KYb = -1j * np.kron(D1y, Iz)
        KZb = -1j * np.kron(Iy, D1z)
        KY2 = np.kron(K2y, Iz) + 0j
        KZ2b = np.kron(Iy, K2z) + 0j
    else:
        raise ValueError(f"unknown basis {basis!r}")
    KX = kx * Ig + c * (By * Zd - Bz * Yd)
    KY = KYb
    KZ = KZb + c * Bx * Yd
    KX2 = KX @ KX
    KZ2 = KZ2b + (2 * c * Bx * _sym(KZb, Yd) + (c * Bx) ** 2 * (Yd @ Yd)
                  if Bx else 0)
    Lp, Mp, Np = _LMN()
    Op = [[None] * 3 for _ in range(3)]
    Op[0][0] = Lp * KX2 + Mp * (KY2 + KZ2)
    Op[1][1] = Lp * KY2 + Mp * (KX2 + KZ2)
    Op[2][2] = Lp * KZ2 + Mp * (KX2 + KY2)
    Op[0][1] = Op[1][0] = Np * _sym(KX, KY)
    Op[1][2] = Op[2][1] = Np * _sym(KY, KZ)
    Op[0][2] = Op[2][0] = Np * _sym(KZ, KX)
    n6 = 6 * ny * nz
    H = np.zeros((n6, n6), complex)
    for a in range(3):
        for b in range(3):
            H += np.kron(Op[a][b], CAB[a][b])
    H += np.kron(QE * Ez_Vm * Zd, I6)
    H += Dso_meV * MEV_J * np.kron(Ig, P7)
    if any(B):
        H += np.kron(Ig, _zeeman6(B))
    return H


def extract6(Ez_Vm, Wy=10e-9, Wz=12e-9, ny=11, nz=13,
             k1=2e7, Btest=0.05, Dso_meV=DSO_MEV, basis="dst"):
    """(m*/m0, alpha_eVA, gx, gy, gz, nso) for the lowest Kramers doublet.
    Identical extraction recipes to lk_holes.extract."""
    kw = dict(Wy=Wy, Wz=Wz, ny=ny, nz=nz, Dso_meV=Dso_meV, basis=basis)
    e0 = np.linalg.eigvalsh(build_fin_H6(0.0, Ez_Vm, (0, 0, 0), **kw))[:2]
    ek = np.linalg.eigvalsh(build_fin_H6(k1, Ez_Vm, (0, 0, 0), **kw))[:2]
    alpha_Jm = (ek[1] - ek[0]) / (2 * k1)
    dE = ek.mean() - e0.mean()
    mstar = HBAR**2 * k1**2 / (2 * dE) / M0 if dE > 0 else np.nan
    gs = []
    for ax in range(3):
        Bv = [0.0, 0.0, 0.0]
        Bv[ax] = Btest
        eb = np.linalg.eigvalsh(build_fin_H6(0.0, Ez_Vm, tuple(Bv), **kw))[:2]
        gs.append((eb[1] - eb[0]) / (MU_B_J * Btest))
    w, v = np.linalg.eigh(build_fin_H6(k1, Ez_Vm, (0, 0, 0), **kw))
    Ng = v.shape[0] // 6
    nso = []
    for Jm in J6:
        Op = np.kron(np.eye(Ng), Jm)
        nso.append(float(np.real(v[:, 0].conj() @ Op @ v[:, 0]
                                 - v[:, 1].conj() @ Op @ v[:, 1])))
    nso = np.array(nso)
    nrm = np.linalg.norm(nso)
    nso = nso / nrm if nrm > 1e-9 else nso
    return (float(mstar), float(alpha_Jm / QE / 1e-10),
            float(gs[0]), float(gs[1]), float(gs[2]), nso.tolist())


def _lso_nm(m, al):
    return HBAR**2 / (m * M0 * al * QE * 1e-10) * 1e9 if al > 1e-6 else np.inf


